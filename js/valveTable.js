export function valveRecommendation(wet, pressure) {
  if (!Number.isFinite(wet) || !Number.isFinite(pressure)) return null;
  if (wet > -1 || pressure < 10 || pressure > 40) return null;
  const temperature = Math.max(-17, Math.ceil(wet));
  const column = PRESSURES.findIndex((p) => p >= pressure);
  return {
    temperature,
    pressure: PRESSURES[column],
    valves: VALVES[-temperature - 1][column].split("+").map(Number),
    coldEnd: wet < -17,
  };
}
